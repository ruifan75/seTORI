-- seTORI → Holodex へセットリストを送った時刻。
--
-- **外部に残る非正規化コピーの台帳。** Holodex への書き戻しは運用者の名義で
-- 向こうのデータベースへ曲名・開始/終了秒を書き込む（`PUT /api/v2/songs`）。
-- あとから配信が秘匿になっても、**seTORI 側を全部伏せても向こうのコピーは残る**。
-- seTORI から取り消す手段は無い（そもそも Holodex が公開している API ではない）。
--
-- 自動で撤回はしない。判断と実行は運用者に委ねるが、**送信を試みたことを
-- 忘れないよう記録して画面に出す**。記録が無いと「何を外へ出したか」を
-- 後から辿れず、秘匿にした時点で気付く手がかりが消える。
--
-- **「送信済み」ではなく「送信を試みた」。** 記録は PUT の前に書く
-- （外部 API と DB は同じ transaction に入れられないので、
-- 「記録はあるが届いていない」＝過剰な警告 のほうへ倒す）。
--
-- **NULL は「送っていない」ではなく「分からない」。** 送信の口はこの migration より前から
-- 動いていたので、過去の送信はここに残っていない。既存行を backfill する手もあるが、
-- Holodex に曲がある理由が seTORI からの送信とは限らず（元から向こうにあった曲も多い）、
-- 機械的には区別できない。そこで画面では **holodex_data に曲があること**も
-- 併せて警告の材料にする ── どちらが理由でも、確認しに行く先は同じ Holodex のページ。
ALTER TABLE streams
    ADD COLUMN IF NOT EXISTS holodex_uploaded_at TIMESTAMPTZ;
